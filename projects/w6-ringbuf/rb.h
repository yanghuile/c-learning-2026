/* ============================================================
 *  rb.h —— 环形缓冲区模块（接口声明）
 *
 *  数据结构练习项目 · W6
 *
 *  ═══════════════════════════════════════════════════════════
 *  和前面的练习相比，这个模块做了两个【工程化设计决策】：
 *  ═══════════════════════════════════════════════════════════
 *
 *  决策 1：缓冲区【由调用方提供】（不放在结构体里）
 *  ─────────────────────────────────────────────────────────
 *    之前：struct { uint8_t buf[8]; ... }   ← 容量写死在类型里
 *    现在：struct { uint8_t *buf; uint32_t capacity; ... }
 *           + rb_init(rb, buf, capacity)     ← 容量运行时决定
 *
 *    为什么这样更好：
 *      - 同一个类型能用于 8 字节的按键缓冲，也能用于 512 字节的串口缓冲
 *      - 调用方可以把 buf 定义成 static（放 .bss，不占栈）
 *        也可以放 DMA 能访问的内存（串口 DMA 接收必需）
 *      - 结构体本身很小（只有指针 + 3 个 uint32）
 *
 *    为什么不用 malloc：
 *      嵌入式怕堆碎片，缓冲一律静态分配
 *
 *  决策 2：溢出策略用【两个函数】表达，不用函数指针
 *  ─────────────────────────────────────────────────────────
 *    rb_put()           满了 → 丢弃新数据，返回 0
 *    rb_put_overwrite() 满了 → 覆盖最旧的数据，返回 1
 *
 *    为什么不用函数指针（回调）：
 *      - 函数指针在中断里调用有额外开销
 *      - 策略是编译期就能定的事，运行时切换很少需要
 *      - 两个明确的函数更好读、更好调试
 *      （但要知道"函数指针"这个选项存在 —— 见 README 的讨论）
 *
 *  ⚠️ 中断安全说明（重要，但先知道概念）：
 *    如果要"中断里写、主循环里读"，本模块【不加锁】也能工作，
 *    前提是：write 只被生产者改，read 只被消费者改。
 *    但 count 字段被两者都改 → 32 位读写是原子的所以安全，
 *    不过 8 位机上需要关中断保护。详见 README。
 * ============================================================ */
#ifndef RB_H
#define RB_H

#include <stdint.h>

/* ============================================================
 *  结构体（完整定义放在头文件里 —— 嵌入式惯例）
 *
 *  为什么不像链表那样用"不透明指针"？
 *    因为嵌入式的缓冲区通常要【静态分配】：
 *        static uint8_t uart_buf[256];
 *        static RingBuf uart_rb;
 *        rb_init(&uart_rb, uart_buf, sizeof(uart_buf));
 *    如果结构体不透明，调用方就没法声明 RingBuf 变量，只能 malloc。
 * ============================================================ */
typedef struct
{
    uint8_t  *buf;          /* 指向调用方提供的数据区（不拥有它，不负责释放） */
    uint32_t  capacity;     /* 容量（字节） */
    uint32_t  read;         /* 下一个要读的下标 */
    uint32_t  write;        /* 下一个要写的下标 */
    uint32_t  count;        /* 当前元素个数（方案 B 的"记账"） */
} RingBuf;

/* ============================================================
 *  一、生命周期
 * ============================================================ */

/* 初始化：把调用方的 buf 交给 rb 管理
 * 参数：buf 数据区，capacity 容量（字节）
 * 返回：1 成功，0 失败（buf 为 NULL 或 capacity 为 0）
 *
 * ⚠️ 本模块不分配内存，所以不需要 destroy —— 但记得：
 *    rb 不拥有 buf，buf 的生命周期由调用方负责 */
int rb_init(RingBuf *rb, uint8_t *buf, uint32_t capacity);

/* 清空（read/write/count 复位，buf 内容不动） */
void rb_clear(RingBuf *rb);

/* ============================================================
 *  二、状态查询
 * ============================================================ */

uint32_t rb_count(const RingBuf *rb);       /* 当前元素个数 */
uint32_t rb_free(const RingBuf *rb);        /* 还能再写几个字节 */
int      rb_is_empty(const RingBuf *rb);    /* 空 → 1 */
int      rb_is_full(const RingBuf *rb);     /* 满 → 1 */

/* ============================================================
 *  三、单个字节读写
 * ============================================================ */

/* 写入一个字节：满了 → 返回 0（丢弃新数据） */
int rb_put(RingBuf *rb, uint8_t data);

/* 写入一个字节：满了 → 覆盖最旧的数据，总是返回 1
 * 用途：传感器最新值、实时数据流（最新的比最旧的更有价值） */
int rb_put_overwrite(RingBuf *rb, uint8_t data);

/* 读出一个字节：空 → 返回 0（且不修改 *data） */
int rb_get(RingBuf *rb, uint8_t *data);

/* ============================================================
 *  四、批量读写（推荐优先使用 —— 效率高）
 * ============================================================ */

/* 一次写入多个字节
 * 返回：实际写入的字节数（0 ~ len）
 * 说明：空间不够就少写（丢弃写不下的），调用方从 src + 返回值 继续 */
uint32_t rb_write(RingBuf *rb, const uint8_t *src, uint32_t len);

/* 一次读出多个字节
 * 返回：实际读出的字节数（0 ~ len）
 * 说明：数据不够就少读，调用方从 dst + 返回值 继续 */
uint32_t rb_read(RingBuf *rb, uint8_t *dst, uint32_t len);

/* ============================================================
 *  五、调试辅助（可选）
 * ============================================================ */

/* 打印当前状态到标准输出（正式固件里可以删掉或重定向到串口） */
void rb_dump(const RingBuf *rb);

#endif /* RB_H */
