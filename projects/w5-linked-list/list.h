/* ============================================================
 *  list.h —— 单链表工具库（接口声明）
 *
 *  数据结构练习项目 · W5
 *
 *  设计原则：
 *    - 这个文件只放【声明】和【类型】，不放实现
 *    - 使用者只需要 #include "list.h"，不需要知道内部怎么实现
 *    - 头文件有 include guard，可以被多次包含
 *
 *  约定：单链表，【不带头节点】（第一个节点就是数据节点）
 * ============================================================ */
#ifndef LIST_H
#define LIST_H

#include <stddef.h>     /* size_t */

/* ============================================================
 *  类型定义
 * ============================================================ */
typedef struct Node
{
    int          data;
    struct Node *next;
} Node;

/* ============================================================
 *  一、生命周期
 * ============================================================ */

/* 创建一个节点，失败返回 NULL */
Node *create_node(int data);

/* 释放整条链表，并把 *head 置为 NULL */
void free_list(Node **head);

/* ============================================================
 *  二、插入
 * ============================================================ */

/* 头插：新节点成为第一个 */
void insert_head(Node **head, int data);

/* 尾插：新节点接在最后 */
void insert_tail(Node **head, int data);

/* 在下标 pos 处插入（pos 从 0 开始）
 * pos == 0 插头部，pos == 长度 插末尾，越界返回 0
 * 成功返回 1，失败返回 0 */
int insert_at(Node **head, int pos, int value);

/* ============================================================
 *  三、删除
 * ============================================================ */

/* 删除第一个值为 value 的节点
 * 删掉了返回 1，没找到或空链表返回 0 */
int delete_value(Node **head, int value);

/* ============================================================
 *  四、查找与统计
 * ============================================================ */

/* 按值查找，返回节点指针，找不到返回 NULL */
Node *find(Node *head, int value);

/* 求长度，空链表返回 0 */
int list_length(Node *head);

/* 找中间节点（快慢指针）
 * 奇数个返回正中间；偶数个返回后中间那个；空链表返回 NULL */
Node *find_middle(Node *head);

/* 求倒数第 k 个节点（快慢指针，只遍历一次）
 * k <= 0 或 k 超过长度或空链表，返回 NULL */
Node *find_kth_from_end(Node *head, int k);

/* 判断是否有环（Floyd 判环）
 * 有环返回 1，无环返回 0 */
int has_cycle(Node *head);

/* ============================================================
 *  五、反转
 * ============================================================ */

/* 迭代法反转，返回新的头 */
Node *reverse_iter(Node *head);

/* 递归法反转，返回新的头 */
Node *reverse_rec(Node *head);

/* 每 k 个节点一组反转，不足 k 个的保持原样
 * k <= 1 时返回原链表 */
Node *reverse_k(Node *head, int k);

/* ============================================================
 *  六、合并与判断
 * ============================================================ */

/* 合并两个有序链表（升序），复用原节点，返回新头 */
Node *merge_sorted(Node *a, Node *b);

/* 判断是否回文，是返回 1，否返回 0（空链表算回文） */
int is_palindrome(Node *head);

/* ============================================================
 *  七、输出与便利函数
 * ============================================================ */

/* 打印链表，格式：1 -> 2 -> 3 -> NULL；空链表打印 (空链表) */
void print_list(Node *head);

/* 从数组建一条链表，返回头指针 */
Node *list_from_array(const int *arr, int n);

#endif /* LIST_H */
